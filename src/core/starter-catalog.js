/**
 * Retrieve deep-cloned starter catalog compounds and templates,
 * optionally filtered by `sectionIds`.
 */
export function getStarterCatalog(options = {}) {
  const { sectionIds = null } = options || {};
  const secFilter = Array.isArray(sectionIds) && sectionIds.length > 0 ? new Set(sectionIds) : null;
  const compounds = STARTER_COMPOUNDS
    .filter((c) => !secFilter || secFilter.has(c.sectionId))
    .map((c) => deepClone(c));

  const includedIds = new Set(compounds.map((c) => c.id));
  const stackTemplates = STARTER_STACK_TEMPLATES
    .filter((t) => !secFilter || t.items.some((it) => includedIds.has(it.compoundId)))
    .map((t) => deepClone(t));

  return {
    version: STARTER_CATALOG_VERSION,
    generatedAt: STARTER_CATALOG_DATE,
    compounds,
    stackTemplates,
  };
}

/**
 * Idempotently seed the generic starter catalog into a HubState.
 * Never mutates caller `state`, never overwrites user-edited profiles,
 * and skips exact/alias/id duplicates cleanly on repeat invocations.
 */
export function seedStarterCatalog(state, options = {}) {
  const {
    sectionIds = null,
    createOwnershipRecords = false,
    defaultOwnershipStatus = 'dont_have',
    nowIso = new Date().toISOString(),
  } = options || {};
  const safeNow = typeof nowIso === 'string' && nowIso.trim() ? nowIso : new Date().toISOString();
  const nextState = deepClone(state && typeof state === 'object' && !Array.isArray(state) ? state : {});
  nextState.compounds = Array.isArray(nextState.compounds) ? nextState.compounds : [];
  nextState.ownership = Array.isArray(nextState.ownership) ? nextState.ownership : [];

  const catalog = getStarterCatalog({ sectionIds });
  const existingIdSet = new Set(nextState.compounds.map((c) => c?.id).filter(Boolean));
  const existingSlugSet = new Set(nextState.compounds.map((c) => c?.slug).filter(Boolean));
  const ownStatus = OWNERSHIP_STATUSES.includes(defaultOwnershipStatus) ? defaultOwnershipStatus : 'dont_have';

  let added = 0;
  let skipped = 0;
  const addedIds = [];

  for (const starter of catalog.compounds) {
    if (existingIdSet.has(starter.id) || existingSlugSet.has(starter.slug)) {
      skipped++;
      continue;
    }
    const dup = checkDuplicateCompound(starter, nextState.compounds);
    if (dup.isDuplicate) {
      skipped++;
      continue;
    }

    const stamped = {
      ...starter,
      createdAt: safeNow,
      updatedAt: safeNow,
    };
    nextState.compounds.push(stamped);
    existingIdSet.add(stamped.id);
    existingSlugSet.add(stamped.slug);
    added++;
    addedIds.push(stamped.id);

    if (createOwnershipRecords) {
      const ownId = `own_${stamped.id}_household`;
      if (!nextState.ownership.some((o) => o && o.id === ownId)) {
        nextState.ownership.push({
          id: ownId,
          compoundId: stamped.id,
          scope: 'household',
          status: ownStatus,
          updatedAt: safeNow,
        });
      }
    }
  }

  return {
    state: nextState,
    added,
    skipped,
    addedIds,
  };
}
